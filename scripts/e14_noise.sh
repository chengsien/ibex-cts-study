#!/usr/bin/env bash
# e14_noise.sh — more routing-perturbation noise probes (E14; E5 had only 2).
# Each probe branches from R0a with the default CTS (clock tree identical to
# RA) and changes only the metal2-metal3 global-routing capacity adjustment
# right before global route (PRE_GLOBAL_ROUTE_TCL hook, as in E5).
#   usage: scripts/e14_noise.sh 0.44 0.46 ...      (runs N_gr44, N_gr46, ...)
# Per probe: full CTS->route->RCX flow, clock reports, then the per-endpoint
# dumps that summarize.py / e14_noise.py use for the clock/data split.
set -uo pipefail
cd "$(dirname "$0")/.."
IMG="${ORFS_IMAGE:-openroad/orfs:26Q4-260-gc9ac73efc}"
probe() {
  local v=$1 tag=${1#0.}; local n=N_gr$tag
  local hook=scripts/noise_grt_adj_$tag.tcl
  # complete = the last dump is newer than the run's own final database (a
  # branch copies the base run's reports, so existence alone is not enough)
  local ca=runs/$n/reports/nangate45/ibex/base/ck_arrivals_final.csv
  if [[ -f $ca && $ca -nt runs/$n/results/nangate45/ibex/base/6_final.odb ]]; then echo "[$n] already complete"; return 0; fi
  if [[ ! -f $hook ]]; then
    cat > "$hook" <<EOF
# Noise probe (PRE_GLOBAL_ROUTE_TCL), generated by scripts/e14_noise.sh:
# re-set the metal2-metal3 global-routing capacity adjustment from the
# platform's 0.5 to $v right before global route. Clock tree and placement
# are untouched; only routing is perturbed (see noise_grt_adj_48.tcl).
utl::info FLW 911 "noise probe: metal2-metal3 layer adjustment -> $v"
set_global_routing_layer_adjustment metal2-metal3 $v
EOF
  fi
  if [[ ! -f runs/$n/results/nangate45/ibex/base/6_final.odb ]]; then
    scripts/run.sh -n "$n" -p 2.2 -b R0a -e PRE_GLOBAL_ROUTE_TCL=/work/$hook || { echo "[$n] flow failed"; return 1; }
  fi
  scripts/post_reports.sh "$n"
  for s in worst_paths endpoint_slack dump_ck_arrivals; do
    scripts/sta_run.sh "$n" scripts/$s.tcl $s >/dev/null 2>&1 || echo "[$n] $s failed"
  done
  grep -h FLW-0911 runs/$n/logs/nangate45/ibex/base/*.log | head -1
  echo "[$n] done"
}
for v in "$@"; do probe "$v"; done
echo E14_DONE
