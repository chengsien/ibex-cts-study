#!/usr/bin/env bash
# e16_auto.sh — automated select -> build -> route loop for launch-side
# useful skew (E16).
#   usage: scripts/e16_auto.sh [prefix] [base_run] [max_iter] [pre_hook]
#     prefix   run-name prefix (default E16), runs are <prefix>_1, _2, ...
#     base_run routed run the first selection is made on (default RA)
#     pre_hook optional POST_CTS script applied before the moves in every
#              iteration (e.g. scripts/rd_phys2_T30.tcl for a capture+launch
#              combination); base_run must then be the run built with it
# Iteration k: e16_select.tcl on the routed result of iteration k-1 ->
# candidates; build <prefix>_k from R0a's placement with e16_hook.tcl, which
# re-applies the moves accepted so far and greedily tries the new candidates
# with a whole-design STA guard; route + RCX; stop when post-route setup WNS
# improves by less than 1 ps, when no move is kept, or after max_iter.
set -uo pipefail
cd "$(dirname "$0")/.."
PFX=${1:-E16}; PREV=${2:-RA}; KMAX=${3:-4}; PRE=${4:-}
SUB=nangate45/ibex/base
wns() { grep -m1 '^setup_wns_ns=' "runs/$1/reports/$SUB/clock_final.kv" | cut -d= -f2; }
mkdir -p scripts/e16
best=$PREV; bw=$(wns "$PREV"); moves_in=""
echo "[$PFX] start from $PREV  WNS=$bw"
for k in $(seq 1 "$KMAX"); do
  n=${PFX}_$k
  scripts/sta_run.sh "$PREV" scripts/e16_select.tcl e16_select -e E16_T=0.050 -e E16_N=40 2>&1 | grep E16SEL
  cands=runs/$PREV/reports/$SUB/e16_cands.txt
  [[ -s $cands ]] || { echo "[$PFX] no candidates file"; break; }
  [[ -f runs/$PREV/reports/$SUB/e16_moves_out.txt ]] && moves_in=/work/runs/$PREV/reports/$SUB/e16_moves_out.txt
  w=scripts/e16/${n}.tcl
  {
    echo "# generated by scripts/e16_auto.sh: iteration $k of $PFX"
    echo "set e16_tag $n"
    echo "set e16_T 0.050"
    [[ -n ${E16_WNS_TOL:-} ]] && echo "set e16_wns_tol $E16_WNS_TOL"
    echo "set e16_prev_wns $(wns "$PREV")"
    echo "set e16_cands_file /work/$cands"
    echo "set e16_moves_in \"$moves_in\""
    [[ -n $PRE ]] && echo "set e16_pre /work/$PRE"
    echo "source /work/scripts/e16_hook.tcl"
  } > "$w"
  if [[ ! -f runs/$n/results/$SUB/6_final.odb ]]; then
    scripts/run.sh -n "$n" -p 2.2 -b R0a -t "$w" || { echo "[$n] flow failed"; break; }
  fi
  scripts/post_reports.sh "$n" >/dev/null
  for s in worst_paths endpoint_slack dump_ck_arrivals; do
    scripts/sta_run.sh "$n" scripts/$s.tcl $s >/dev/null 2>&1 || echo "[$n] $s failed"
  done
  kept=$(grep -c . "runs/$n/reports/$SUB/e16_moves_out.txt" 2>/dev/null || echo 0)
  nw=$(wns "$n")
  echo "[$n] post-route WNS=$nw (prev $bw)  registers moved=$kept  $(tail -1 runs/$n/reports/$SUB/e16_hook.rpt)"
  if python3 -c "import sys; sys.exit(0 if float('$nw') > float('$bw') + 0.001 else 1)"; then
    best=$n; bw=$nw; PREV=$n
  else
    echo "[$PFX] stop: iteration $k did not improve post-route WNS by >= 1 ps (best $best, $bw)"; break
  fi
done
echo "E16_DONE best=$best wns=$bw"
